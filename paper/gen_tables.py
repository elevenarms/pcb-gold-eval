#!/usr/bin/env python3
"""Write paper/tables.tex from data/ (boards, baselines, oracle) and forecast/forecast.json. Stdlib only."""
import glob, json, os, tomllib
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = tomllib.load(open(f"{R}/boards.toml", "rb"))
M = {b: json.load(open(f"{R}/data/meta/{b}.json")) for b in B}
NAME = {"signal-integrity-test-board": "SI test board", "m2-pcie-adapter": "M.2 PCIe adapter", "hdmi-mipi-bridge": "HDMI--MIPI bridge",
        "gmsl-deserializer": "GMSL deserializer", "jetson-orin-baseboard": "Jetson Orin baseboard", "rdimm-ddr4-tester": "RDIMM DDR4 tester",
        "sodimm-ddr5-tester": "SO-DIMM DDR5 tester", "rdimm-ddr5-tester": "RDIMM DDR5 tester"}
HS = {"signal-integrity-test-board": "50\\,$\\Omega$ lines", "m2-pcie-adapter": "PCIe x4", "hdmi-mipi-bridge": "HDMI, CSI-2", "gmsl-deserializer": "GMSL2, CSI-2",
      "jetson-orin-baseboard": "PCIe, USB3, CSI-2", "rdimm-ddr4-tester": "DDR4", "sodimm-ddr5-tester": "DDR5", "rdimm-ddr5-tester": "DDR5"}
out = []
out.append("% generated by gen_tables.py -- do not edit\n\\newcommand{\\boardtable}{%\n\\begin{tabular}{llrrrrl}\\toprule\n"
           "Board & Tier & Cu & Parts & Pair nets & To route & Interfaces\\\\\\midrule")
for b in B:
    s = M[b]["stats"]
    out.append(f"{NAME[b]} & {B[b]['tier']} & {s['copper_layers']} & {s['footprints']} & {s['pair_nets']} & {M[b]['stripped_unconnected']:,} & {HS[b]}\\\\")
out.append("\\bottomrule\\end{tabular}}\n")
best = {}
runs = [json.load(open(f)) for f in glob.glob(f"{R}/data/baselines/*.json")]
for r in runs:
    if r.get("reward") is not None and (r["board"] not in best or r["reward"] > best[r["board"]]["reward"]):
        best[r["board"]] = r
out.append("\\newcommand{\\baselinetable}{%\n\\begin{tabular}{lrrrrrrrr}\\toprule\n"
           "Board & Time (s) & Compl. & DRC & Skew & Length & Width & Eff. & Reward\\\\\\midrule")
for b in B:
    if b in best:
        r = best[b]
        out.append(f"{NAME[b]} & {r['router_seconds']:.0f} & {r['completion']:.2f} & {r['drc']:.2f} & {r['pair_skew']:.2f} & {r['length_groups']:.2f} & {r['impedance_width']:.2f} & {r['efficiency']:.2f} & \\textbf{{{r['reward']:.2f}}}\\\\")
out.append("\\bottomrule\\end{tabular}}\n")
fc = json.load(open(f"{R}/forecast/forecast.json"))
out.append("\\newcommand{\\forecasttable}{%\n\\begin{tabular}{rccc}\\toprule\nBudget & 4 h & 1 day & 1 week\\\\\\midrule")
for bud in (100, 1000, 10000):
    cells = []
    for t in (4, 24, 168):
        m = next(x for x in fc["medium"]["rows"] if x["budget"] == bud and x["hours"] == t)["reward"]
        h = next(x for x in fc["hard"]["rows"] if x["budget"] == bud and x["hours"] == t)["reward"]
        cells.append(f"{m:.2f} / {h:.2f}")
    out.append(f"\\${bud:,} & " + " & ".join(cells) + "\\\\")
out.append("\\bottomrule\\end{tabular}}\n")
oracle = [json.load(open(f)) for f in glob.glob(f"{R}/jobs/oracle-all/*/verifier/reward.json")]
out.append(f"\\newcommand{{\\noracle}}{{{sum(o.get('reward') == 1.0 for o in oracle)}}}\\newcommand{{\\noracleall}}{{{len(oracle)}}}"
           f"\\newcommand{{\\nruns}}{{{len(runs)}}}\\newcommand{{\\nbaseboards}}{{{len(best)}}}")
open(f"{R}/paper/tables.tex", "w").write("\n".join(out) + "\n")
print("tables.tex:", len(best), "boards with baselines;", len(oracle), "oracle trials")
